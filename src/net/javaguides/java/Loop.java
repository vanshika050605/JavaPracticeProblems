package net.javaguides.java;

public class Loop {
    public static void main(String[] args) {
       for (int i=0;i<5;i++){
            System.out.println("Hello World");
       }
    int j=11;
    
    do{
        System.out.println(j);
        j++;

    }
    while(j<10);

    int k=0;
    while(k<11){
        System.out.println(k);
        k++;
    }
}
}
